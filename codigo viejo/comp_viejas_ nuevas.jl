# =========================================================
# MODELO PASCHEN
# =========================================================

function paschen(pd, p)

    B, C, k = p

    x = pd .+ k
    denom = log.(x) .+ C

    return B .* x ./ denom

end


# =========================================================
# AJUSTE
# =========================================================

function ajustar_paschen(pd, V)

    p0 = [300.0, 1.0, 0.5]

    lower = [1.0, -10.0, -1.0]
    upper = [5000.0, 10.0, 2.0]

    fit = curve_fit(
        paschen,
        pd,
        V,
        p0,
        lower = lower,
        upper = upper
    )

    pars = fit.param
    errs = stderror(fit)

    N = length(V)
    npar = length(pars)

    σ_res = sqrt(
        sum(fit.resid.^2) / (N - npar)
    )

    return fit, pars, errs, σ_res

end


# =========================================================
# INCERTIDUMBRES
# =========================================================

Δp = 0.01
Δd = 1.0

ΔV(V) = 0.008 .* V .+ 2

Δpd(p, d) = abs.(p .* d) .* (
    Δp ./ p .+ Δd ./ d
)


# =========================================================
# FUNCIÓN PARA AGREGAR UNA SERIE
# =========================================================

colores = [:blue, :red, :green, :orange]

function agregar_serie!(
    plt,
    p,
    d,
    V,
    nombre,
    color
)

    # ---------------------------------------------
    # pd
    # ---------------------------------------------

    pd = p .* d

    # ---------------------------------------------
    # Incertidumbre en pd
    # ---------------------------------------------

    σpd = Δpd(p, d)

    # ---------------------------------------------
    # Ajuste
    # ---------------------------------------------

    fit, par, err, σ =
        ajustar_paschen(pd, V)

    # ---------------------------------------------
    # Datos experimentales
    # ---------------------------------------------

    scatter!(
        plt,
        pd,
        V,
        ylims = (300, 700),
        xerror = σpd,
        yerror = ΔV(V),
        color = color,
        label = nombre
    )

    # ---------------------------------------------
    # Curva ajustada
    # ---------------------------------------------

    x = range(
        minimum(pd) * 0.8,
        maximum(pd) * 1.1,
        length = 300
    )

    plot!(
        plt,
        x,
        paschen(x, par),
        lw = 3,
        color = color,
        label = ""
    )

end


# =========================================================
# OBTENER DATOS AUTOMÁTICAMENTE
# =========================================================

function obtener_experimento(d, id)

    nombre_p = Symbol("p$(d)$(id)")
    nombre_V = Symbol("V$(d)$(id)")

    p = getfield(Main, nombre_p)
    V = getfield(Main, nombre_V)

    return p, V

end


