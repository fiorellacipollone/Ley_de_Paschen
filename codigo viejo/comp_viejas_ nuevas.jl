subplots = Any[]

for (d, cantidad) in seleccion

    plt = plot(
        title = "$(d) mm",
        xlabel = "pd",
        ylabel = "V (V)",
        legend = :topleft,
        ylims = (300, 700)
    )

    for id in 1:cantidad

        p, V = obtener_experimento(d, id)

        agregar_serie!(
        plt,
        p,
        d,
        V,
        "$(d)$(id)",
        colores[id]
        )

    end

    push!(subplots, plt)

end


