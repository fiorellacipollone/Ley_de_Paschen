# =====================================================
# MODELO PASCHEN
# =====================================================

function paschen(pd, p)

    B, C, k = p

    x = pd .+ k
    denom = log.(x) .+ C

    return B .* x ./ denom

end

# =====================================================
# FUNCIÓN DE AJUSTE
# =====================================================

function ajustar_paschen(pd, V)

    p0 = [300.0, 1.0, 0.5]

    lower = [1.0, -10.0, -1.0]
    upper = [5000.0, 10.0, 2.0]

    fit = curve_fit(
        paschen,
        pd,
        V,
        p0,
        lower=lower,
        upper=upper
    )

    pars = fit.param
    errs = stderror(fit)

    N = length(V)
    npar = length(pars)

    sigma_res = sqrt(sum(fit.resid.^2)/(N-npar))

    return fit, pars, errs, sigma_res

end

